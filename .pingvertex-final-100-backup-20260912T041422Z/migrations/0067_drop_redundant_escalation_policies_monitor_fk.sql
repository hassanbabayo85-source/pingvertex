-- Follow-up to 0065 (SEC-P0-3 tenant-integrity migration).
--
-- 0065 added the new composite FK
-- `fk_escalation_policies_monitor_tenant (monitor_id, tenant_id)` on
-- escalation_policies, but — unlike api_flows, maintenance_windows, and
-- notification_channels in that same migration — it never dropped the
-- original single-column FK `escalation_policies_monitor_id_fkey`
-- (monitor_id -> monitors(id)), created back in migration 0017.
--
-- Verified by inspecting every migration 0018-0066: no later migration
-- touches or renames that constraint, so it is still present alongside
-- the new composite FK today. Two FKs enforcing overlapping referential
-- integrity on the same column is redundant (extra trigger/lock work on
-- every write and delete of a monitor or escalation_policies row) and a
-- future maintenance hazard, so this migration removes the stale one.
--
-- IF_EXISTS guard: safe to run even if the constraint name differs from
-- what's expected, or if 0065 is ever re-applied to a fresh DB in a form
-- that already omits the old FK.
ALTER TABLE escalation_policies
    DROP CONSTRAINT IF EXISTS escalation_policies_monitor_id_fkey;
