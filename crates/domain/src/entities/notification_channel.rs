use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};

use crate::{
    enums::NotificationChannelKind,
    shared::ids::{MonitorId, NotificationChannelId, UserId},
    value_objects::{Email, Url},
};

/// Data required to create a new email notification channel.
#[derive(Debug, Clone)]
pub struct CreateEmailChannel {
    pub id: NotificationChannelId,
    pub monitor_id: MonitorId,
    pub user_id: UserId,
    pub email: Email,
}

/// Data required to create a new webhook notification channel.
#[derive(Debug, Clone)]
pub struct CreateWebhookChannel {
    pub id: NotificationChannelId,
    pub monitor_id: MonitorId,
    pub user_id: UserId,
    pub url: Url,
    /// High-entropy HMAC signing secret. Generated by the caller (the
    /// infra layer, via `IdGenerator::next_webhook_signing_secret`) —
    /// randomness generation is I/O-adjacent, so the domain entity only
    /// stores the value handed to it, it never generates secrets itself.
    pub signing_secret: String,
}

/// A user-configured destination that should be notified when a monitor
/// goes down or recovers.
///
/// `target` holds the already-validated email address or webhook URL
/// (validated by the `Email`/`Url` value objects at construction time, see
/// `create_email`/`create_webhook` below). `signing_secret` is only ever
/// populated for `Webhook` channels — see the `chk_notification_channels_*`
/// constraints in `migrations/0010_create_notification_channels.sql`, which
/// enforce the same invariant at the database level.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct NotificationChannel {
    pub id: NotificationChannelId,
    pub monitor_id: MonitorId,
    /// Denormalized copy of the owning monitor's `user_id`.
    ///
    /// Kept directly on the channel (rather than requiring a join through
    /// `monitors` for every check) so ownership can still be enforced with
    /// a single indexed `WHERE id = $1 AND user_id = $2` — the same
    /// pattern the rest of this codebase uses for monitors/incidents —
    /// while the Postgres repository ALSO joins through `monitors` on
    /// writes, so a channel can never end up with a `user_id` that
    /// disagrees with the monitor it belongs to.
    pub user_id: UserId,
    pub kind: NotificationChannelKind,
    pub target: String,
    pub signing_secret: Option<String>,
    pub enabled: bool,
    pub created_at: DateTime<Utc>,
    pub updated_at: DateTime<Utc>,
}

impl NotificationChannel {
    pub fn create_email(input: CreateEmailChannel) -> Self {
        let now = Utc::now();

        Self {
            id: input.id,
            monitor_id: input.monitor_id,
            user_id: input.user_id,
            kind: NotificationChannelKind::Email,
            target: input.email.into_string(),
            signing_secret: None,
            enabled: true,
            created_at: now,
            updated_at: now,
        }
    }

    pub fn create_webhook(input: CreateWebhookChannel) -> Self {
        let now = Utc::now();

        Self {
            id: input.id,
            monitor_id: input.monitor_id,
            user_id: input.user_id,
            kind: NotificationChannelKind::Webhook,
            target: input.url.as_str().to_owned(),
            signing_secret: Some(input.signing_secret),
            enabled: true,
            created_at: now,
            updated_at: now,
        }
    }

    pub fn disable(&mut self) {
        self.enabled = false;
        self.updated_at = Utc::now();
    }

    pub fn enable(&mut self) {
        self.enabled = true;
        self.updated_at = Utc::now();
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use uuid::Uuid;

    fn ids() -> (NotificationChannelId, MonitorId, UserId) {
        (
            NotificationChannelId(Uuid::new_v4()),
            MonitorId(Uuid::new_v4()),
            UserId(Uuid::new_v4()),
        )
    }

    #[test]
    fn create_email_has_no_signing_secret() {
        let (id, monitor_id, user_id) = ids();

        let channel = NotificationChannel::create_email(CreateEmailChannel {
            id,
            monitor_id,
            user_id,
            email: Email::new("owner@example.com").unwrap(),
        });

        assert_eq!(channel.kind, NotificationChannelKind::Email);
        assert_eq!(channel.target, "owner@example.com");
        assert_eq!(channel.signing_secret, None);
        assert!(channel.enabled);
    }

    #[test]
    fn create_webhook_carries_signing_secret() {
        let (id, monitor_id, user_id) = ids();

        let channel = NotificationChannel::create_webhook(CreateWebhookChannel {
            id,
            monitor_id,
            user_id,
            url: Url::new("https://hooks.example.com/abc").unwrap(),
            signing_secret: "whsec_test".to_string(),
        });

        assert_eq!(channel.kind, NotificationChannelKind::Webhook);
        assert_eq!(channel.signing_secret.as_deref(), Some("whsec_test"));
    }

    #[test]
    fn disable_then_enable_flips_flag() {
        let (id, monitor_id, user_id) = ids();

        let mut channel = NotificationChannel::create_email(CreateEmailChannel {
            id,
            monitor_id,
            user_id,
            email: Email::new("owner@example.com").unwrap(),
        });

        channel.disable();
        assert!(!channel.enabled);

        channel.enable();
        assert!(channel.enabled);
    }
}
